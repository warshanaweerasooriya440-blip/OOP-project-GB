package com.feedback.admin.request;


/** The data the Administrator types in to create or change an LIC. */
public final class LICRequest {
    private final String name;
    private final String email;

    public LICRequest(String name, String email) {
        this.name = name;
        this.email = email;
    }

    public String getName() { return name; }
    public String getEmail() { return email; }
}

